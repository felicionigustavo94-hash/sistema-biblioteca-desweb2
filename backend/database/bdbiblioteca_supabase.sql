-- Remove privilegios de API padrao e devolve somente os necessarios.
REVOKE ALL ON public.bibliotecas, public.autores, public.clientes,
    public.bibliotecarios, public.livros, public.emprestimos,
    public.solicitacoes FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO authenticated;
GRANT SELECT ON public.bibliotecas, public.autores, public.livros,
    public.clientes, public.bibliotecarios, public.emprestimos,
    public.solicitacoes TO authenticated;
GRANT INSERT, UPDATE, DELETE ON public.bibliotecas, public.autores TO authenticated;
GRANT INSERT, DELETE ON public.livros TO authenticated;
