    id_autor, id_biblioteca) ON public.livros TO authenticated;
GRANT UPDATE (nome, telefone, cpf) ON public.clientes TO authenticated;
GRANT INSERT, UPDATE ON public.emprestimos TO authenticated;
GRANT INSERT, UPDATE ON public.solicitacoes TO authenticated;

