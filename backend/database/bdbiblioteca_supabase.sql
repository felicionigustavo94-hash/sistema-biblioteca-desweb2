DROP POLICY IF EXISTS livros_gerenciar ON public.livros;
DROP POLICY IF EXISTS clientes_ler ON public.clientes;
DROP POLICY IF EXISTS clientes_atualizar_proprio ON public.clientes;
DROP POLICY IF EXISTS bibliotecarios_ler ON public.bibliotecarios;
DROP POLICY IF EXISTS emprestimos_ler ON public.emprestimos;
DROP POLICY IF EXISTS emprestimos_criar ON public.emprestimos;
