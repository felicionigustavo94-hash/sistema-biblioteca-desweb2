CREATE POLICY bibliotecas_ler ON public.bibliotecas
FOR SELECT TO authenticated USING (true);
CREATE POLICY bibliotecas_gerenciar ON public.bibliotecas
FOR ALL TO authenticated
USING ((SELECT public.eh_bibliotecario()))
WITH CHECK ((SELECT public.eh_bibliotecario()));

CREATE POLICY autores_ler ON public.autores
FOR SELECT TO authenticated USING (true);
CREATE POLICY autores_gerenciar ON public.autores
FOR ALL TO authenticated
USING ((SELECT public.eh_bibliotecario()))
WITH CHECK ((SELECT public.eh_bibliotecario()));

CREATE POLICY livros_ler ON public.livros
FOR SELECT TO authenticated USING (true);
CREATE POLICY livros_gerenciar ON public.livros
FOR ALL TO authenticated
USING ((SELECT public.eh_bibliotecario()))
WITH CHECK ((SELECT public.eh_bibliotecario()));

CREATE POLICY clientes_ler ON public.clientes
FOR SELECT TO authenticated
USING (auth_user_id = (SELECT auth.uid())
    OR (SELECT public.eh_bibliotecario()));
CREATE POLICY clientes_atualizar_proprio ON public.clientes
FOR UPDATE TO authenticated
USING (auth_user_id = (SELECT auth.uid()))
WITH CHECK (auth_user_id = (SELECT auth.uid()));

CREATE POLICY bibliotecarios_ler ON public.bibliotecarios
FOR SELECT TO authenticated
USING ((SELECT public.eh_bibliotecario()));

CREATE POLICY emprestimos_ler ON public.emprestimos
FOR SELECT TO authenticated
USING (id_cliente = (SELECT public.meu_id_cliente())
    OR (SELECT public.eh_bibliotecario()));
CREATE POLICY emprestimos_criar ON public.emprestimos
FOR INSERT TO authenticated
WITH CHECK (
    (SELECT public.eh_bibliotecario())
    AND id_bibliotecario_entrega = (SELECT public.meu_id_bibliotecario())
    AND status = 'EMPRESTADO'
);
CREATE POLICY emprestimos_atualizar ON public.emprestimos
FOR UPDATE TO authenticated
USING ((SELECT public.eh_bibliotecario()))
WITH CHECK ((SELECT public.eh_bibliotecario()));

CREATE POLICY solicitacoes_ler ON public.solicitacoes
FOR SELECT TO authenticated
USING (id_cliente = (SELECT public.meu_id_cliente())
    OR (SELECT public.eh_bibliotecario()));
CREATE POLICY solicitacoes_criar ON public.solicitacoes
FOR INSERT TO authenticated
WITH CHECK (
    id_cliente = (SELECT public.meu_id_cliente())
    AND status = 'PENDENTE'
);
CREATE POLICY solicitacoes_analisar ON public.solicitacoes
FOR UPDATE TO authenticated
USING ((SELECT public.eh_bibliotecario()))
WITH CHECK ((SELECT public.eh_bibliotecario()));

-- 7. CONSULTA PARA EXIBIR ATRASO (sem guardar status que envelhece) ----------
-- Postgres 15+: security_invoker faz a view respeitar o RLS das tabelas.
CREATE OR REPLACE VIEW public.v_emprestimos_status
WITH (security_invoker = true) AS
SELECT e.id_emprestimo, e.id_cliente, e.id_livro,
    e.data_retirada, e.data_prevista_devolucao,
    e.data_devolucao_real, e.id_bibliotecario_entrega,
    e.id_bibliotecario_devolucao,
    CASE
        WHEN e.status = 'EMPRESTADO'
             AND e.data_prevista_devolucao < CURRENT_DATE
        THEN 'ATRASADO'
        ELSE e.status
    END AS status_atual
FROM public.emprestimos e;
REVOKE ALL ON public.v_emprestimos_status FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.v_emprestimos_status TO authenticated;

