BEGIN;

-- 1. ESTRUTURA ---------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.bibliotecas (
    id_biblioteca integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(100) NOT NULL,
    endereco varchar(200),
    data_fundacao date,
    horario_abertura time NOT NULL,
    horario_fechamento time NOT NULL
);

CREATE TABLE IF NOT EXISTS public.autores (
    id_autor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome varchar(100) NOT NULL,
    nacionalidade varchar(50)
);

CREATE TABLE IF NOT EXISTS public.clientes (
    id_cliente integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id uuid UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
    nome varchar(100) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    cpf varchar(14) UNIQUE,
    telefone varchar(20),
    data_cadastro timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.bibliotecarios (
    id_bibliotecario integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id uuid NOT NULL UNIQUE REFERENCES auth.users(id) ON DELETE RESTRICT,
    nome varchar(100) NOT NULL,
    email varchar(255) NOT NULL UNIQUE,
    cpf varchar(14) UNIQUE,
    turno varchar(20),
    id_biblioteca integer REFERENCES public.bibliotecas(id_biblioteca)
        ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS public.livros (
    id_livro integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo varchar(150) NOT NULL,
    tema varchar(80),
    secao varchar(50),
    edicao varchar(20),
    quantidade_total integer NOT NULL DEFAULT 1,
    quantidade_disponivel integer NOT NULL DEFAULT 1,
    id_autor integer REFERENCES public.autores(id_autor) ON DELETE RESTRICT,
    id_biblioteca integer REFERENCES public.bibliotecas(id_biblioteca)
        ON DELETE RESTRICT,
    CONSTRAINT chk_estoque_livros CHECK (
        quantidade_total >= 0
        AND quantidade_disponivel >= 0
        AND quantidade_disponivel <= quantidade_total
    )
);

CREATE TABLE IF NOT EXISTS public.emprestimos (
    id_emprestimo integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_retirada timestamptz NOT NULL DEFAULT now(),
    data_prevista_devolucao date NOT NULL,
    data_devolucao_real timestamptz,
    status varchar(20) NOT NULL DEFAULT 'EMPRESTADO',
    id_livro integer NOT NULL REFERENCES public.livros(id_livro)
        ON DELETE RESTRICT,
    id_cliente integer NOT NULL REFERENCES public.clientes(id_cliente)
        ON DELETE RESTRICT,
    id_bibliotecario_entrega integer NOT NULL
        REFERENCES public.bibliotecarios(id_bibliotecario) ON DELETE RESTRICT,
    id_bibliotecario_devolucao integer
        REFERENCES public.bibliotecarios(id_bibliotecario) ON DELETE RESTRICT,
    CONSTRAINT chk_status_emprestimo CHECK (
        status IN ('EMPRESTADO', 'DEVOLVIDO')
    ),
    CONSTRAINT chk_devolucao_emprestimo CHECK (
        (status = 'EMPRESTADO' AND data_devolucao_real IS NULL
            AND id_bibliotecario_devolucao IS NULL)
        OR
        (status = 'DEVOLVIDO' AND data_devolucao_real IS NOT NULL)
    ),
    CONSTRAINT chk_prazo_emprestimo CHECK (
        data_prevista_devolucao >= (data_retirada AT TIME ZONE 'UTC')::date
    )
);

CREATE TABLE IF NOT EXISTS public.solicitacoes (
    id_solicitacao integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_solicitacao timestamptz NOT NULL DEFAULT now(),
    status varchar(20) NOT NULL DEFAULT 'PENDENTE',
    id_cliente integer NOT NULL REFERENCES public.clientes(id_cliente)
        ON DELETE RESTRICT,
    id_livro integer NOT NULL REFERENCES public.livros(id_livro)
        ON DELETE RESTRICT,
    CONSTRAINT chk_status_solicitacao CHECK (
        status IN ('PENDENTE', 'APROVADA', 'RECUSADA', 'CANCELADA')
    )
);

-- 2. INDICES (chaves estrangeiras nao geram indices automaticamente) ---------

CREATE INDEX IF NOT EXISTS idx_bibliotecarios_biblioteca
    ON public.bibliotecarios(id_biblioteca);
CREATE INDEX IF NOT EXISTS idx_livros_autor ON public.livros(id_autor);
CREATE INDEX IF NOT EXISTS idx_livros_biblioteca ON public.livros(id_biblioteca);
CREATE INDEX IF NOT EXISTS idx_emprestimos_cliente ON public.emprestimos(id_cliente);
CREATE INDEX IF NOT EXISTS idx_emprestimos_livro ON public.emprestimos(id_livro);
CREATE INDEX IF NOT EXISTS idx_emprestimos_bib_entrega
    ON public.emprestimos(id_bibliotecario_entrega);
CREATE INDEX IF NOT EXISTS idx_emprestimos_bib_devolucao
    ON public.emprestimos(id_bibliotecario_devolucao);
CREATE INDEX IF NOT EXISTS idx_solicitacoes_cliente
    ON public.solicitacoes(id_cliente);
CREATE INDEX IF NOT EXISTS idx_solicitacoes_livro
    ON public.solicitacoes(id_livro);
CREATE UNIQUE INDEX IF NOT EXISTS uq_solicitacao_pendente_cliente_livro
    ON public.solicitacoes(id_cliente, id_livro)
    WHERE status = 'PENDENTE';

-- 3. IDENTIFICACAO DO USUARIO AUTENTICADO -----------------------------------
-- SECURITY DEFINER evita recursao RLS quando uma politica precisa verificar
-- a tabela bibliotecarios. search_path vazio previne objetos maliciosos.

CREATE OR REPLACE FUNCTION public.eh_bibliotecario()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.bibliotecarios b
        WHERE b.auth_user_id = (SELECT auth.uid())
    );
$$;

CREATE OR REPLACE FUNCTION public.meu_id_bibliotecario()
RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT b.id_bibliotecario FROM public.bibliotecarios b
    WHERE b.auth_user_id = (SELECT auth.uid());
$$;

CREATE OR REPLACE FUNCTION public.meu_id_cliente()
RETURNS integer
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = ''
AS $$
    SELECT c.id_cliente FROM public.clientes c
    WHERE c.auth_user_id = (SELECT auth.uid());
$$;

REVOKE ALL ON FUNCTION public.eh_bibliotecario() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.meu_id_bibliotecario() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.meu_id_cliente() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.eh_bibliotecario() TO authenticated;
GRANT EXECUTE ON FUNCTION public.meu_id_bibliotecario() TO authenticated;
GRANT EXECUTE ON FUNCTION public.meu_id_cliente() TO authenticated;

-- 4. CADASTRO AUTOMATICO DO PERFIL DO CLIENTE -------------------------------
-- Criar usuario: supabase.auth.signUp({ email, password, options: {
--   data: { nome: 'Nome da pessoa' } } });
-- Nunca grave senhas nas tabelas public.clientes / public.bibliotecarios.

CREATE OR REPLACE FUNCTION public.criar_cliente_apos_signup()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    -- O sistema de biblioteca utiliza autenticacao por email.
    -- Usuarios Auth somente com telefone, sem email, nao recebem perfil.
    IF NEW.email IS NOT NULL THEN
        INSERT INTO public.clientes (auth_user_id, nome, email)
        VALUES (
            NEW.id,
            LEFT(
                COALESCE(
                    NULLIF(BTRIM(NEW.raw_user_meta_data ->> 'nome'), ''),
                    'Novo cliente'
                ), 100
            ),
            NEW.email
        )
        ON CONFLICT (auth_user_id) DO NOTHING;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_cliente_apos_signup ON auth.users;
CREATE TRIGGER trg_cliente_apos_signup
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.criar_cliente_apos_signup();

-- Atualiza emails de perfis se o email da conta Auth mudar.
CREATE OR REPLACE FUNCTION public.sincronizar_email_auth()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
BEGIN
    IF NEW.email IS DISTINCT FROM OLD.email AND NEW.email IS NOT NULL THEN
        UPDATE public.clientes SET email = NEW.email
        WHERE auth_user_id = NEW.id;
        UPDATE public.bibliotecarios SET email = NEW.email
        WHERE auth_user_id = NEW.id;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_sincronizar_email_auth ON auth.users;
CREATE TRIGGER trg_sincronizar_email_auth
AFTER UPDATE OF email ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.sincronizar_email_auth();

REVOKE ALL ON FUNCTION public.criar_cliente_apos_signup() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.sincronizar_email_auth() FROM PUBLIC, anon, authenticated;

-- 5. ESTOQUE AUTOMATICO DOS LIVROS -----------------------------------------
-- Cadastro: quantidade_disponivel inicia igual a quantidade_total.
-- Aumento/reducao de quantidade_total ajusta o disponivel pela diferenca.
-- Nao se pode reduzir o total abaixo da quantidade emprestada.

CREATE OR REPLACE FUNCTION public.ajustar_estoque_livros()
RETURNS trigger
LANGUAGE plpgsql SET search_path = ''
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.quantidade_disponivel := NEW.quantidade_total;
    ELSIF NEW.quantidade_total IS DISTINCT FROM OLD.quantidade_total THEN
        NEW.quantidade_disponivel := OLD.quantidade_disponivel
            + (NEW.quantidade_total - OLD.quantidade_total);
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_ajustar_estoque_livros ON public.livros;
CREATE TRIGGER trg_ajustar_estoque_livros
BEFORE INSERT OR UPDATE ON public.livros
FOR EACH ROW EXECUTE FUNCTION public.ajustar_estoque_livros();

-- Insercao de emprestimo: decremento atomico de estoque (seguro contra
-- concorrencia). Devolucao: incremento do estoque e registro automatico
-- da data e do bibliotecario responsavel. Nao permite excluir historico,
-- trocar livro/cliente, reabrir devolucao ou falsificar devolucao.

CREATE OR REPLACE FUNCTION public.controlar_estoque_emprestimos()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = ''
AS $$
DECLARE
    v_bibliotecario integer;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Nao exclua emprestimos: mantenha o historico';
    END IF;

    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'EMPRESTADO'
           OR NEW.data_devolucao_real IS NOT NULL
           OR NEW.id_bibliotecario_devolucao IS NOT NULL THEN
            RAISE EXCEPTION 'Um emprestimo novo deve iniciar como EMPRESTADO';
        END IF;

        UPDATE public.livros
        SET quantidade_disponivel = quantidade_disponivel - 1
        WHERE id_livro = NEW.id_livro AND quantidade_disponivel > 0;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Livro inexistente ou sem exemplares disponiveis';
        END IF;
        RETURN NEW;
    END IF;

    -- Somente UPDATE: campos de identificacao e auditoria sao imutaveis.
    IF NEW.id_livro IS DISTINCT FROM OLD.id_livro
       OR NEW.id_cliente IS DISTINCT FROM OLD.id_cliente
       OR NEW.id_bibliotecario_entrega IS DISTINCT FROM OLD.id_bibliotecario_entrega
       OR NEW.data_retirada IS DISTINCT FROM OLD.data_retirada
       OR NEW.data_devolucao_real IS DISTINCT FROM OLD.data_devolucao_real
       OR NEW.id_bibliotecario_devolucao IS DISTINCT FROM OLD.id_bibliotecario_devolucao THEN
        RAISE EXCEPTION 'Nao e permitido alterar dados imutaveis do emprestimo';
    END IF;

    IF OLD.status = 'DEVOLVIDO' THEN
        RAISE EXCEPTION 'Emprestimos devolvidos nao podem ser alterados';
    END IF;

    IF NEW.status = 'DEVOLVIDO' THEN
        SELECT b.id_bibliotecario INTO v_bibliotecario
        FROM public.bibliotecarios b
        WHERE b.auth_user_id = auth.uid();

        -- SQL Editor (administrador) e chamadas internas podem nao ter auth.uid().
        -- Pelo site, o RLS so permite a operacao para bibliotecarios autenticados.
        NEW.data_devolucao_real := now();
        NEW.id_bibliotecario_devolucao := v_bibliotecario;

        UPDATE public.livros
        SET quantidade_disponivel = quantidade_disponivel + 1
        WHERE id_livro = NEW.id_livro;
    ELSIF NEW.status <> 'EMPRESTADO' THEN
        RAISE EXCEPTION 'Transicao de status invalida';
    END IF;
    -- Para emprestimos em aberto, permite alterar apenas o prazo de devolucao.
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_controlar_estoque_emprestimos ON public.emprestimos;
CREATE TRIGGER trg_controlar_estoque_emprestimos
BEFORE INSERT OR UPDATE OR DELETE ON public.emprestimos
FOR EACH ROW EXECUTE FUNCTION public.controlar_estoque_emprestimos();

REVOKE ALL ON FUNCTION public.controlar_estoque_emprestimos() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.ajustar_estoque_livros() FROM PUBLIC, anon, authenticated;

-- Solicitações: nao permite trocar cliente, livro ou data, nem reabrir uma
-- solicitacao ja analisada. Emprestimo nao nasce automaticamente da aprovacao;
-- o bibliotecario precisa registrar a retirada na tabela emprestimos.
CREATE OR REPLACE FUNCTION public.validar_atualizacao_solicitacoes()
RETURNS trigger
LANGUAGE plpgsql SET search_path = ''
AS $$
BEGIN
    IF NEW.id_cliente IS DISTINCT FROM OLD.id_cliente
       OR NEW.id_livro IS DISTINCT FROM OLD.id_livro
       OR NEW.data_solicitacao IS DISTINCT FROM OLD.data_solicitacao THEN
        RAISE EXCEPTION 'Nao e permitido trocar cliente, livro ou data da solicitacao';
    END IF;
    IF OLD.status <> 'PENDENTE' AND NEW.status IS DISTINCT FROM OLD.status THEN
        RAISE EXCEPTION 'Solicitacoes finalizadas nao podem ser reabertas';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_atualizacao_solicitacoes ON public.solicitacoes;
CREATE TRIGGER trg_validar_atualizacao_solicitacoes
BEFORE UPDATE ON public.solicitacoes
FOR EACH ROW EXECUTE FUNCTION public.validar_atualizacao_solicitacoes();
REVOKE ALL ON FUNCTION public.validar_atualizacao_solicitacoes() FROM PUBLIC, anon, authenticated;

-- 6. SEGURANCA (RLS) -------------------------------------------------------
-- Authenticated: catalogo visivel, clientes veem somente seus proprios dados,
-- bibliotecarios gerenciam o catalogo/solicitacoes/emprestimos.
-- A concessao de acesso de bibliotecario acontece apenas por SQL/admin.

ALTER TABLE public.bibliotecas ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.autores ENABLE ROW LEVEL SECURITY;
