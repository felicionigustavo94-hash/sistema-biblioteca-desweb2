-- Nao e preciso expor privilegios gerais sobre sequencias na API.

-- Tira politicas antigas com os nomes abaixo caso este script seja refeito.
DROP POLICY IF EXISTS bibliotecas_ler ON public.bibliotecas;
DROP POLICY IF EXISTS bibliotecas_gerenciar ON public.bibliotecas;
